use super::*;
use indoc::formatdoc;

use truapi::markers::{MARKERS, Marker, MarkerClass, Severity};

/// Generates `markers.ts` under `output_dir`. The file carries the core's
/// marker table to the web hosts, which UniFFI cannot reach and which
/// therefore cannot call `core_markers()`. It is the same table, read from
/// the same list, so the two surfaces cannot disagree.
pub fn generate(output_dir: &str) -> Result<()> {
	fs::create_dir_all(output_dir)?;
	fs::write(Path::new(output_dir).join("markers.ts"), markers_code())?;
	Ok(())
}

fn markers_code() -> String {
	let mut entries = String::new();
	for marker in MARKERS {
		writeln!(entries, "  {},", map_entry(marker)).unwrap();
	}

	formatdoc!(
		r#"
        // Auto-generated by truapi-codegen. Do not edit.

        /** How loud an exported marker is once a host's logger has it. */
        export type MarkerSeverity = "info" | "warn" | "error";

        /** Whether a marker may leave the device, and at what severity if it may. */
        export type MarkerClass =
          | {{ readonly kind: "local" }}
          | {{ readonly kind: "export"; readonly severity: MarkerSeverity }};

        /**
         * Every marker the core may address to a host, keyed by its dotted target.
         *
         * A host reads this once and looks each marker it is handed up here. A
         * target this map does not hold stays on the device, because nothing has
         * said what its detail carries.
         */
        export const CORE_MARKERS: ReadonlyMap<string, MarkerClass> = new Map<string, MarkerClass>([
        {entries}]);
        "#
	)
}

/// One `[target, class]` pair of the emitted map.
fn map_entry(marker: &Marker) -> String {
	let class = match marker.class {
		MarkerClass::Local => r#"{ kind: "local" }"#.to_string(),
		MarkerClass::Export { severity } => {
			format!(r#"{{ kind: "export", severity: "{}" }}"#, severity_name(severity))
		},
	};
	format!("[{}, {class}]", ts_string_literal(marker.target))
}

fn severity_name(severity: Severity) -> &'static str {
	match severity {
		Severity::Info => "info",
		Severity::Warn => "warn",
		Severity::Error => "error",
	}
}

